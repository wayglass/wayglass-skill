#!/bin/sh
# Write scripts/cli-surface.txt from a wayglass binary's --help output: one
# line per command, its path then every flag it accepts. scripts/check.sh
# checks each wayglass command the skills mention against this file, so a
# skill cannot name a command or flag the CLI does not have.
#
# Usage: scripts/snapshot-cli.sh [path/to/wayglass]   (default: wayglass on PATH)
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
bin=${1:-wayglass}
if ! command -v "$bin" >/dev/null 2>&1; then
  echo "error: $bin not found; build it from the wayglass repo (go build ./cmd/wayglass)" >&2
  exit 1
fi

# subcommands prints the names under "Available Commands:" in a help text.
subcommands() {
  awk '/^Available Commands:/ { on = 1; next } on && /^$/ { exit } on { print $1 }'
}

# flags prints every long flag (and its short form) from Flags and Global Flags.
flags() {
  awk '/^(Global )?Flags:/ { on = 1; next } on && /^$/ { on = 0 } on {
    # Only the first two fields name flags ("-m, --message string"); the
    # description can contain anything.
    for (i = 1; i <= 2 && i <= NF; i++) if ($i ~ /^--?[a-z]/) { f = $i; sub(/,$/, "", f); print f }
  }' | sort -u | tr '\n' ' ' | sed 's/ $//'
}

walk() {
  # "$@" is the command path below the root.
  help=$("$bin" "$@" --help)
  printf '%s\t%s\n' "wayglass${*:+ $*}" "$(printf '%s\n' "$help" | flags)"
  for sub in $(printf '%s\n' "$help" | subcommands); do
    case $sub in help|completion) continue ;; esac
    walk "$@" "$sub"
  done
}

{
  echo "# Generated by scripts/snapshot-cli.sh from $("$bin" version 2>/dev/null | head -1). Do not edit by hand."
  walk
} > "$root/scripts/cli-surface.txt"
echo "wrote scripts/cli-surface.txt"
